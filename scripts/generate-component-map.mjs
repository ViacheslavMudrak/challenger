// Generates src/lib/component-map.ts - a component map for the Content SDK SitecoreProvider.
//
// Why this exists:
//   Sitecore renderings on this site use DOTTED names (e.g. 'Nav.brand', 'Footer.main.links',
//   'Banner.template1', 'ColumnContainer.sitecore'), and Content SDK resolves components by an
//   EXACT lookup: componentMap.get(rendering.componentName). The default generated map
//   (temp/componentBuilder) only registers folder-level / non-dotted names, so dotted renderings
//   fall back to the orange "component is missing React implementation" placeholder.
//
// What it does:
//   Scans src/components for every component file (.tsx with a default OR named/variant export) and
//   registers it by its file basename (= the Sitecore rendering name), on top of the generated map
//   (which still provides built-ins like BYOCWrapper / FEaaSWrapper).
//
// Run:  npm run generate:component-map     (or: node scripts/generate-component-map.mjs)

import fs from 'node:fs';

const ROOT = 'src/components';
const OUT = 'src/lib/component-map.ts';
const EXCLUDE_DIRS = ['__stories__', '__tests__', 'mocks'];

/** @type {{ p: string, base: string }[]} */
const files = [];

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = `${dir}/${entry.name}`;
    if (entry.isDirectory()) {
      if (!EXCLUDE_DIRS.includes(entry.name)) walk(p);
    } else if (
      entry.name.endsWith('.tsx') &&
      !entry.name.includes('.stories.') &&
      !entry.name.includes('.test.')
    ) {
      const content = fs.readFileSync(p, 'utf8');
      const isComponent =
        content.includes('export default') ||
        content.includes('export const ') ||
        content.includes('export function ');
      if (isComponent) files.push({ p, base: entry.name.slice(0, -4) });
    }
  }
}

walk(ROOT);

// Dedupe by Sitecore rendering name (file basename); first match wins.
const seen = new Set();
const picked = [];
for (const f of files) {
  if (!seen.has(f.base)) {
    seen.add(f.base);
    picked.push(f);
  }
}
picked.sort((a, b) => a.base.localeCompare(b.base));

const imports = [];
const sets = [];
const usedAlias = new Set();
for (const f of picked) {
  const importPath = f.p.slice(0, -4); // strip .tsx
  let alias = importPath.replace('src/', '').replace(/[^a-zA-Z0-9]/g, '_');
  while (usedAlias.has(alias)) alias += '_';
  usedAlias.add(alias);
  imports.push(`import * as ${alias} from '${importPath}';`);
  sets.push(`componentMap.set('${f.base}', ${alias});`);
}

const out = `import { ComponentMap } from '@sitecore-content-sdk/nextjs';
import { componentMap as generated } from 'temp/componentBuilder';

// AUTO-GENERATED by scripts/generate-component-map.mjs - DO NOT EDIT BY HAND.
// Registers every component under src/components by its file basename (the Sitecore rendering name),
// on top of the generated temp/componentBuilder map. Needed because Sitecore renderings use dotted
// names and Content SDK resolves components via exact componentMap.get(name).
// Re-run after adding/removing components: npm run generate:component-map
${imports.join('\n')}

export const componentMap: ComponentMap = new Map(generated);

${sets.join('\n')}

export default componentMap;
`;

fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT} with ${picked.length} components.`);
